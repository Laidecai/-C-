/*
 * 题号：P03-01
 * 题目：使用条件运算符求两个整数最大值
 * 考点：对应《C程序设计（第五版）》第三章中的 条件运算符 ?:、整型输入输出。
 * 解题思路：
 * 1) 先将输入数据读取到变量中，明确每个变量在内存中的值。
 * 2) 按表达式求值顺序逐步计算中间结果，避免一次性“心算跳步”。
 * 3) 将最终结果按题目要求格式化输出，并处理非法输入场景。
 */

#include <stdio.h>

int main(void) {
    int a, b;

    if (scanf("%d%d", &a, &b) != 2) {
        puts("输入错误");
        return 1;
    }

    int max_value = (a > b) ? a : b;
    printf("%d\n", max_value);
    return 0;
}

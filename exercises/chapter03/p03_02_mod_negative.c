/*
 * 题号：P03-02
 * 题目：验证负数取模结果
 * 考点：对应《C程序设计（第五版）》第三章中的 取模运算 %、输入校验（除数不能为 0）。
 * 解题思路：
 * 1) 先将输入数据读取到变量中，明确每个变量在内存中的值。
 * 2) 按表达式求值顺序逐步计算中间结果，避免一次性“心算跳步”。
 * 3) 将最终结果按题目要求格式化输出，并处理非法输入场景。
 */

#include <stdio.h>

int main(void) {
    int a, b;

    if (scanf("%d%d", &a, &b) != 2) {
        puts("输入错误");
        return 1;
    }

    if (b == 0) {
        puts("除数不能为0");
        return 1;
    }

    printf("%d\n", a % b);
    return 0;
}
